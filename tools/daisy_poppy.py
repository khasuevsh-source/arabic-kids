def norm(s):
    s = re.sub(r"[ً-ٰٟـ]", "", s)
    s = re.sub(r"[أإآٱ]", "ا", s).replace("ى", "ي").replace("ة", "ه")
    return re.sub(r"[^ء-ي]", "", s)


def main():
    src, out = sys.argv[1], sys.argv[2]
    raw = json.load(open(src, encoding="utf-8"))["lines"]
    lines = []
    for i, r in enumerate(raw, 1):
        fix = LINES.get(i, "missing")
        if fix == "missing":
            raise SystemExit(f"Нет исправления для строки {i}: {r['ar']}")
        if fix is None:
            continue
        lines.append({"s": r["start"], "e": r["end"], "ar": fix[0], "ru": fix[1]})

    gl = {norm(k): v for k, v in GLOSSARY.items()}
    missing = set()
    for l in lines:
        for w in l["ar"].split():
            n = norm(w)
            if not n or n in gl:
                continue
            if not any(n.startswith(p) and n[len(p):] in gl for p in map(norm, PREFIXES)):
                missing.add(n)
    if missing:
        print("Нет в словарике:", " ".join(sorted(missing)))

